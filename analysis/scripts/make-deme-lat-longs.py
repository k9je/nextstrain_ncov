#!/usr/bin/env python3
"""
Build a `deme`-keyed lat/longs TSV for `augur export v2 --lat-longs`.

Auspice can only place a deme on the map -- and therefore can only draw a
transmission line touching it -- if that deme has coordinates. Because our
demes are a mixture of country names (inside Asia) and region names (outside
it), neither Augur's `country` nor its `region` coordinates suffice on their
own, so we emit a `deme` row for every deme actually present in the metadata.

Coordinates are looked up in this order:
  1. the extra file (custom demes such as Caribbean / Central America)
  2. Augur's built-in `country` coordinates
  3. Augur's built-in `region` coordinates

A deme with no coordinates anywhere is a hard error: silently omitting it would
quietly erase it, and every transmission line into or out of it, from the map.
"""
import argparse
import os
import sys


def read_lat_longs(path):
    """Read a 4-column lat/longs TSV into {(geo_resolution, value): (lat, long)}.

    Keys are lower-cased to match Augur's own case-insensitive lookup.
    """
    coordinates = {}
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.rstrip("\n").rstrip("\r")
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            fields = line.split("\t") if "\t" in line else line.split()
            if len(fields) != 4:
                continue
            geo_resolution, value, lat, lon = fields
            try:
                coordinates[(geo_resolution.strip().lower(), value.strip().lower())] = (
                    float(lat),
                    float(lon),
                )
            except ValueError:
                continue
    return coordinates


def augur_lat_longs_path():
    import augur

    return os.path.join(os.path.dirname(augur.__file__), "data", "lat_longs.tsv")


def read_demes(metadata_path, deme_column):
    """Return the distinct deme values in the metadata, in first-seen order."""
    demes = []
    seen = set()
    with open(metadata_path, encoding="utf-8") as fh:
        header_line = fh.readline().rstrip("\n").rstrip("\r")
        header = header_line.split("\t")
        if deme_column not in header:
            raise ValueError(
                f"{metadata_path} has no {deme_column!r} column; found: {header}"
            )
        idx = header.index(deme_column)
        for line in fh:
            line = line.rstrip("\n").rstrip("\r")
            if not line:
                continue
            fields = line.split("\t")
            if idx >= len(fields):
                continue
            value = fields[idx].strip()
            if not value or value == "?":
                continue
            if value not in seen:
                seen.add(value)
                demes.append(value)
    return demes


def main():
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--metadata", required=True, help="metadata TSV containing the deme column")
    parser.add_argument("--extra-lat-longs", required=True, help="custom centroids TSV")
    parser.add_argument("--deme-column", default="deme")
    parser.add_argument("--output", required=True, help="output lat/longs TSV")
    args = parser.parse_args()

    extra = read_lat_longs(args.extra_lat_longs)
    builtin = read_lat_longs(augur_lat_longs_path())

    demes = read_demes(args.metadata, args.deme_column)

    rows = []
    missing = []
    for deme in demes:
        key = deme.lower()
        for source_name, table, resolution in (
            ("extra", extra, "deme"),
            ("augur:country", builtin, "country"),
            ("augur:region", builtin, "region"),
        ):
            coordinates = table.get((resolution, key))
            if coordinates is not None:
                rows.append((deme, coordinates[0], coordinates[1], source_name))
                break
        else:
            missing.append(deme)

    if missing:
        print(
            "ERROR: no coordinates found for these demes:\n  "
            + "\n  ".join(sorted(missing))
            + f"\n\nAdd them to {args.extra_lat_longs} and re-run.",
            file=sys.stderr,
        )
        sys.exit(1)

    with open(args.output, "w", encoding="utf-8") as fh:
        fh.write("# Generated by scripts/make-deme-lat-longs.py -- do not edit by hand.\n")
        for deme, lat, lon, _source in sorted(rows):
            fh.write(f"deme\t{deme}\t{lat}\t{lon}\n")
        # Also pass through the extra `country` rows so that the `country`
        # geo-resolution keeps working for countries Augur does not know.
        with open(args.extra_lat_longs, encoding="utf-8") as extra_fh:
            for line in extra_fh:
                stripped = line.rstrip("\n").rstrip("\r")
                if stripped.startswith("country\t"):
                    fh.write(stripped + "\n")

    print(f"make-deme-lat-longs: wrote coordinates for {len(rows)} demes", file=sys.stderr)
    for deme, lat, lon, source in sorted(rows):
        print(f"  {deme:<24} {lat:>11.5f} {lon:>12.5f}   [{source}]", file=sys.stderr)


if __name__ == "__main__":
    main()
